import { BrowserGame } from "./browser_game.ts";
import { assert, assertEquals, assertStringIncludes } from "./test_asserts.ts";

function game(): BrowserGame {
  return new BrowserGame([
    { deu: "Guten Tag", eng: "Good day", nwords: 2 },
    { deu: "Danke schön", eng: "Thank you", nwords: 2 },
  ]);
}

Deno.test("BrowserGame handles hints, translations and wrong answers", () => {
  const browser = game();
  browser.answer("  ");
  assertEquals(browser.message, "");
  browser.hint();
  assertEquals(browser.message, "Hint: Guten");
  browser.hint(2);
  assertEquals(browser.message, "Hint: Guten Tag");
  browser.translate();
  assertEquals(browser.message, "English: Good day");
  browser.answer("Falsch");
  assertStringIncludes(browser.message, "Falsch. Try again");
  assertEquals(browser.index, 0);
});

Deno.test("BrowserGame advances, completes and restarts", () => {
  const browser = game();
  browser.answer(" Guten Tag ");
  assertEquals(browser.index, 1);
  assertEquals(browser.message, "Richtig! English: Good day");
  browser.answer("Danke schön");
  assertEquals(browser.index, 2);
  assertStringIncludes(browser.message, "You completed the game");
  assertEquals(browser.current, undefined);

  browser.restart();
  assertEquals(browser.index, 0);
  assertEquals(browser.message, "Game restarted.");
  assertEquals(browser.jumbles.length, 2);
  assert(browser.current);
  assertEquals(browser.current.end, false);
});

Deno.test("BrowserGame advances for a real dataset sentence containing NBSP", () => {
  const browser = new BrowserGame([
    { deu: "Dieses Auto fährt 60\u00a0km/h.", eng: "This car drives 60 km/h.", nwords: 5 },
  ]);
  // This is the value generated by dragging the tiles into the displayed order.
  browser.answer("Dieses Auto fährt 60 km/h.");
  assertEquals(browser.index, 1);
  assertStringIncludes(browser.message, "Richtig!");
});

Deno.test("commands after completion do not replace the final message", () => {
  const browser = game();
  browser.answer("Guten Tag");
  browser.answer("Danke schön");
  const message = browser.message;
  browser.hint();
  browser.translate();
  browser.answer("Guten Tag");
  assertEquals(browser.message, message);
});
